#Requires -Version 7.0
<#
.SYNOPSIS
Generates a local GitHub Wiki portal from the versioned documentation indexes.
.EXAMPLE
./scripts/prepare-wiki.ps1
.EXAMPLE
./scripts/prepare-wiki.ps1 -OutputDirectory out/wiki-preview
#>
[CmdletBinding()]
param(
    [string] $OutputDirectory = 'out/wiki'
)

$ErrorActionPreference = 'Stop'
$projectRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$comparison = if ($IsWindows) { [StringComparison]::OrdinalIgnoreCase } else { [StringComparison]::Ordinal }
$separator = [IO.Path]::DirectorySeparatorChar
$blobBase = 'https://github.com/naldodj/hb.bridge/blob/main/'
$wikiBase = 'https://github.com/naldodj/hb.bridge/wiki/'
$outRoot = [IO.Path]::GetFullPath((Join-Path $projectRoot 'out'))
$outputPath = [IO.Path]::GetFullPath($(if ([IO.Path]::IsPathRooted($OutputDirectory)) { $OutputDirectory } else { Join-Path $projectRoot $OutputDirectory }))
$sources = [ordered]@{
    'Home.md' = [IO.Path]::GetFullPath((Join-Path $projectRoot 'docs/README.md'))
    'Home.pt-BR.md' = [IO.Path]::GetFullPath((Join-Path $projectRoot 'docs/README.pt-BR.md'))
}
$pages = [ordered]@{}
$pattern = '(?<prefix>\[[^\]\r\n]*\]\()(?:(?<angle><)(?<target>[^>\r\n]+)>|(?<target>[^\s)]+))(?<title>\s+"[^"\r\n]*")?\)'
$utf8 = [Text.UTF8Encoding]::new($false)

function Test-ContainedPath {
    param([string] $Path, [string] $Parent)

    return $Path.Equals($Parent, $comparison) -or $Path.StartsWith($Parent.TrimEnd($separator) + $separator, $comparison)
}

function Assert-SafeAncestry {
    param([string] $Path)

    $ancestor = $Path
    while ($ancestor) {
        $item = Get-Item -LiteralPath $ancestor -Force -ErrorAction SilentlyContinue
        if ($item -and ($item.Attributes -band [IO.FileAttributes]::ReparsePoint)) {
            throw 'Wiki generation cannot follow a symbolic link or junction.'
        }
        $ancestor = [IO.Path]::GetDirectoryName($ancestor)
    }
}

function Convert-WikiTarget {
    param([string] $Target, [string] $SourcePath)

    if ($Target -match '^(?:#|//|[A-Za-z][A-Za-z0-9+.-]*:)') { return $Target }
    $fragmentPosition = $Target.IndexOf('#')
    $fragment = if ($fragmentPosition -ge 0) { $Target.Substring($fragmentPosition) } else { '' }
    $localTarget = if ($fragmentPosition -ge 0) { $Target.Substring(0, $fragmentPosition) } else { $Target }
    $localTarget = [Uri]::UnescapeDataString($localTarget)
    if ($localTarget.StartsWith('/')) {
        $resolved = [IO.Path]::GetFullPath((Join-Path $projectRoot $localTarget.TrimStart('/')))
    } else {
        $resolved = [IO.Path]::GetFullPath((Join-Path ([IO.Path]::GetDirectoryName($SourcePath)) $localTarget))
    }
    if (-not (Test-ContainedPath $resolved $projectRoot)) { throw "Wiki link leaves the repository: $Target" }
    if (-not (Test-Path -LiteralPath $resolved)) { throw "Wiki link target does not exist: $Target" }
    foreach ($page in $sources.Keys) {
        if ($resolved.Equals($sources[$page], $comparison)) {
            return $wikiBase + [IO.Path]::GetFileNameWithoutExtension($page) + $fragment
        }
    }
    $relative = [IO.Path]::GetRelativePath($projectRoot, $resolved).Replace('\', '/')
    $encoded = ($relative.Split('/') | ForEach-Object { [Uri]::EscapeDataString($_) }) -join '/'
    return $blobBase + $encoded + $fragment
}

if (-not (Test-ContainedPath $outputPath $outRoot) -or $outputPath.Equals($outRoot, $comparison)) {
    throw '-OutputDirectory must be a subdirectory of the project out directory.'
}
Assert-SafeAncestry $outputPath
foreach ($page in $sources.Keys) {
    $sourcePath = $sources[$page]
    Assert-SafeAncestry $sourcePath
    $content = [IO.File]::ReadAllText($sourcePath).Replace("`r`n", "`n")
    $converted = [regex]::Replace($content, $pattern, [Text.RegularExpressions.MatchEvaluator] {
        param($match)

        $target = Convert-WikiTarget $match.Groups['target'].Value $sourcePath
        $destination = if ($match.Groups['angle'].Success) { '<' + $target + '>' } else { $target }
        return $match.Groups['prefix'].Value + $destination + $match.Groups['title'].Value + ')'
    })
    $relativeSource = [IO.Path]::GetRelativePath($projectRoot, $sourcePath).Replace('\', '/')
    $pages[$page] = "<!-- Generated by scripts/prepare-wiki.ps1 from $relativeSource. Edit the versioned source. -->`n`n" + $converted.TrimEnd() + "`n"
}
$pages['_Sidebar.md'] = @"
[English](${wikiBase}Home) · [Português (Brasil)](${wikiBase}Home.pt-BR)

[Repository / Repositório](https://github.com/naldodj/hb.bridge)

[Documentation source](${blobBase}docs/README.md) · [Fonte da documentação](${blobBase}docs/README.pt-BR.md)
"@ + "`n"
$pages['_Footer.md'] = @"
Guides remain versioned in ``docs/`` alongside the code. This portal is generated from [docs/README.md](${blobBase}docs/README.md) and [docs/README.pt-BR.md](${blobBase}docs/README.pt-BR.md); edit those sources and regenerate the Wiki pages.

Os guias permanecem versionados em ``docs/`` junto ao código. Este portal é gerado a partir desses índices em inglês e português; as alterações devem ser feitas nas fontes e as páginas da Wiki geradas novamente.
"@ + "`n"

# Resolve every source link before creating or replacing generated files.
foreach ($page in $pages.Keys) {
    Assert-SafeAncestry (Join-Path $outputPath $page)
}
[void][IO.Directory]::CreateDirectory($outputPath)
foreach ($page in $pages.Keys) {
    [IO.File]::WriteAllText((Join-Path $outputPath $page), $pages[$page], $utf8)
}
Write-Host "Wiki preview generated: $outputPath (4 files). No publication was performed."
